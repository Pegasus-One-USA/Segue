using FHIRBridge.Domain.Enums;

namespace FHIRBridge.Application.DTOs.Mapping;

/// <summary>
/// Generic destination-field description the schema matching engine scores against — deliberately not tied to
/// <see cref="DestinationColumnSchemaDto"/> so the engine isn't coupled to SQL-shaped destinations. Callers that
/// already have SQL/FHIR-repository schema metadata should go through <see cref="FromDestinationColumn"/> rather
/// than hand-building this record.
/// </summary>
public sealed record FhirFieldMetadata(
    string Name,
    MappingValueType DataType,
    bool IsRequired = false,
    string? Description = null)
{
    public static FhirFieldMetadata FromDestinationColumn(DestinationColumnSchemaDto column) =>
        new(
            column.Name,
            ParseMappingValueType(column.MappingValueType),
            IsRequired: !column.IsNullable && !column.IsAutoGenerated);

    private static MappingValueType ParseMappingValueType(string value) =>
        Enum.TryParse<MappingValueType>(value, ignoreCase: true, out var parsed) ? parsed : MappingValueType.String;
}

/// <summary>
/// One destination field's best-matching source field, with the full weighted-score breakdown for
/// explainability. Returned for every requested destination field regardless of score — the 0.90 / 0.70
/// auto-select / highlight bands are a UI concern, not a service-level filter.
/// </summary>
public sealed record FieldMappingSuggestion(
    string DestinationField,
    string? SourceField,
    double Confidence,
    double NameScore,
    double SynonymScore,
    double TypeScore,
    double ValueScore,
    double StructureScore,
    string Reason);

/// <summary>One user-approved (or rejected) destination-to-source decision, submitted via SaveApprovedMappingAsync.</summary>
public sealed record ApprovedMappingRequest(
    string DestinationField,
    string SourceField,
    double Confidence = 1.0,
    bool Approved = true);
